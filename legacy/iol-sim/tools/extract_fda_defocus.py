"""Extract the binocular defocus curves (Vivity DFT015 and SN60WF monofocal control) from the FDA Summary of Safety
and Effectiveness Data for PMA P930014/S126 (public-domain US government document), Figures 9 and 10, into
data/defocusCurves.js.

Run from the iol-sim folder:  python tools/extract_fda_defocus.py   (requires pymupdf)

Method: the figures are vector graphics, so values are read from the drawing coordinates, not from pixels.
- Axes are calibrated per page from the centres of the '0.00' / '1.00' logMAR labels and the '+1.5' / '0.0' D labels.
- Mean curves = the two black polylines (solid = Vivity, dashed = monofocal); each vertex is one data point.
- 95% CI (Fig 9, p.45) and +/-1 SD (Fig 10, p.46) = vertical error-bar segments at each point.
- Check: the drawn CI half-width matches 1.96*SD/sqrt(n) (n = 106 / 111) within 0.001 logMAR at every point.
Calibration uncertainty (label centre vs tick): about +/-0.003 logMAR.
"""
import json, math
from pathlib import Path
import pymupdf

ROOT = Path(__file__).resolve().parent.parent
doc = pymupdf.open(ROOT / 'data' / 'source' / 'FDA_SSED_P930014S126_Vivity.pdf')


def read_page(pn):
    pg = doc[pn - 1]
    w = {t[4]: ((t[0] + t[2]) / 2, (t[1] + t[3]) / 2) for t in pg.get_text('words')}
    y0, y1, x15, x00 = w['0.00'][1], w['1.00'][1], w['+1.5'][0], w['0.0'][0]
    Y = lambda y: (y - y0) / (y1 - y0)
    X = lambda x: (x00 - x) / (x00 - x15) * 1.5
    series, vsegs = {}, []
    for d in pg.get_drawings():
        if d.get('color') != (0.0, 0.0, 0.0):
            continue
        segs = [it for it in d['items'] if it[0] == 'l']
        if len(segs) >= 4:
            pts = [segs[0][1]] + [s[2] for s in segs]
            if max(p.x for p in pts) - min(p.x for p in pts) > 200:
                name = 'monofocal' if d.get('dashes') and '2.87' in str(d['dashes']) else 'vivity'
                series[name] = [(round(X(p.x) * 4) / 4, Y(p.y)) for p in pts]
                continue
        for s in segs:
            a, b = s[1], s[2]
            if abs(a.x - b.x) < 0.2 and abs(a.y - b.y) > 1.5:
                vsegs.append((X(a.x), Y(min(a.y, b.y)), Y(max(a.y, b.y))))
    res = {}
    for name, pts in series.items():
        rows = []
        for dD, m in pts:
            c = [v for v in vsegs if abs(v[0] - dD) < 0.08 and v[1] - 0.002 <= m <= v[2] + 0.002]
            rows.append((dD, m, min(v[1] for v in c), max(v[2] for v in c)))
        res[name] = sorted(rows, key=lambda r: -r[0])
    return res


ci, sd = read_page(45), read_page(46)
out = {}
for name, n in [('vivity', 106), ('monofocal', 111)]:
    pts = []
    for (d, m, lo, hi), (_, m2, slo, shi) in zip(ci[name], sd[name]):
        s = (shi - slo) / 2
        assert abs(m - m2) < 0.002, 'means differ between figures'
        assert abs((hi - lo) / 2 - 1.96 * s / math.sqrt(n)) < 0.002, 'CI does not match SD/sqrt(n)'
        pts.append({'d': d, 'va': round(m, 3), 'lo': round(lo, 3), 'hi': round(hi, 3), 'sd': round(s, 3)})
    out[name] = {'n': n, 'points': pts}

(ROOT / 'data' / 'defocusCurves.js').write_text(
    '// GENERATED by tools/extract_fda_defocus.py — do not edit by hand.\n'
    '// Binocular mean defocus curves, 6 months, all implanted; FDA SSED P930014/S126 Figs 9-10. lo/hi = 95% CI.\n'
    'window.DEFOCUS_CURVES = ' + json.dumps(out) + ';\n', encoding='utf-8')
print('wrote data/defocusCurves.js:', {k: len(v['points']) for k, v in out.items()}, 'points; all CI/SD checks passed')
