"""Extract the Vivity +20 D radial power profile from the Garzon et al. 2024 dataset (Zenodo 10.5281/zenodo.18084296,
CC BY 4.0) into data/vivityPowerProfile.js.

Run from the iol-sim folder:  python tools/extract_vivity.py   (requires openpyxl)
Processing: mean of the 10 NIMO repeat measurements (M01-M10) at each radial position, then the two half-meridians
(-r and +r) averaged. No smoothing, interpolation or extrapolation.
"""
import json
from pathlib import Path
from statistics import mean, pstdev
import openpyxl

ROOT = Path(__file__).resolve().parent.parent
wb = openpyxl.load_workbook(ROOT / 'data' / 'source' / 'Garzon2024_Dataset_Vivity.xlsx', data_only=True)
rows = [r for r in wb['Power Profile'].iter_rows(min_row=2, values_only=True) if r[2] == '+20.00 D' and r[3] == 'Centered']
by_r = {round(r[0], 2): [float(v) for v in r[4:14]] for r in rows}

r_mm, power, sd = [], [], []
for key in sorted(k for k in by_r if k >= 0):
    sides = [by_r[key]] + ([by_r[-key]] if -key in by_r and key != 0 else [])
    vals = [v for s in sides for v in s]
    r_mm.append(key); power.append(round(mean(vals), 4)); sd.append(round(pstdev(vals), 4))

out = {
    'source': 'Garzon N et al., Graefes Arch Clin Exp Ophthalmol 2024;262:2897-2906 (doi 10.1007/s00417-024-06469-y); '
              'dataset doi 10.5281/zenodo.18084296 (CC BY 4.0)',
    'lens': 'AcrySof IQ Vivity DFT015, +20.00 D, centred', 'instrument': 'NIMO TR1504, 546 nm',
    'processing': 'mean of 10 repeat measurements, both half-meridians averaged; no smoothing',
    'rMm': r_mm, 'powerD': power, 'sdD': sd,
}
(ROOT / 'data' / 'vivityPowerProfile.js').write_text(
    '// GENERATED by tools/extract_vivity.py — do not edit by hand.\nwindow.VIVITY_POWER_PROFILE = ' + json.dumps(out) + ';\n',
    encoding='utf-8')
print(len(r_mm), 'points, r', r_mm[0], '-', r_mm[-1], 'mm; max SD', max(sd), 'D')
